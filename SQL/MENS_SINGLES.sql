#WINDOW FUNCTION 
WITH LEE_TACS AS (
SELECT
TOURNAMENT,
YEAR,
COUNT(*) AS TOTAL_MATCHES
FROM LEE_SINGLES
GROUP BY TOURNAMENT, YEAR
)
SELECT *,
DENSE_RANK() OVER (ORDER BY TOTAL_MATCHES DESC) AS TOURNAMENT_RANK
FROM LEE_TACS;

#LAG FUNCTION 
