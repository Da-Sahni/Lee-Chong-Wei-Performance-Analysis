DATE,MONTH, YEAR, TOURNAMENT, OPPONENT,
LAG(OPPONENT) OVER (PARTITION BY YEAR ORDER BY DATE) AS PREVIOUS_OPPONENT
FROM LEE_SINGLES;

#LEAD 
